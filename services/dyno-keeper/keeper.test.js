test("keeper plans from one pinned block after verifying its RPC chain", async () => {
  const keeper = new DynoKeeper({ rpcUrl: "http://127.0.0.1:1", chainId: 2020, managerAddress: "0x0000000000000000000000000000000000000001", vaultAddress: "0x0000000000000000000000000000000000000002" });
  const observed = [];
  keeper.provider.send = async () => "0x7e4";
  keeper.provider.getBlock = async () => ({ number: 42, timestamp: 3601 });
  keeper.manager.activeRoundId = async at => { observed.push(at.blockTag); return 2n; };
  keeper.manager.getRoundStatus = async (_roundId, at) => { observed.push(at.blockTag); return { phase: Phase.SETTLED }; };
  keeper.vault.getSchedule = async at => { observed.push(at.blockTag); return { state: Schedule.ACTIVE, startsAt: 1n, endsAt: 604801n }; };
  keeper.vault.getSlotStatus = async (_slot, at) => { observed.push(at.blockTag); return 0n; };
  keeper.vault.terminalSlotCount = async at => { observed.push(at.blockTag); return 0n; };
  const result = await keeper.tick();
  assert.deepEqual(observed, [42, 42, 42, 42, 42]);
  assert.equal(result.roundId, "2");
  assert.deepEqual(result.actions.map(action => action.method), ["executeCurrentSlot", "markExpiredSlots"]);
  assert.ok(result.actions.every(action => action.dryRun));
  keeper.provider.destroy();
});
test("keeper follows a replacement round by default and permits an explicit pinned override", async () => {
  const options = { rpcUrl: "http://127.0.0.1:1", chainId: 2020, managerAddress: "0x0000000000000000000000000000000000000001", vaultAddress: "0x0000000000000000000000000000000000000002" };
  const keeper = new DynoKeeper(options);
  keeper.provider.send = async () => "0x7e4";
  keeper.provider.getBlock = async () => ({ number: 44, timestamp: 100 });
  let active = 1n;
  keeper.manager.activeRoundId = async () => active;
  keeper.manager.getRoundStatus = async id => ({ phase: id === 2n ? Phase.FROZEN : 0n });
  keeper.vault.getSchedule = async () => ({ state: 0n, endsAt: 0n });
  assert.equal((await keeper.tick()).roundId, "1");
  active = 2n;
  const next = await keeper.tick();
  assert.equal(next.roundId, "2"); assert.deepEqual(next.actions.map(action => action.method), ["requestDraw"]);
  keeper.provider.destroy();
  const pinned = new DynoKeeper({ ...options, roundId: "7" });
  pinned.provider.send = async () => "0x7e4";
  pinned.provider.getBlock = async () => ({ number: 44, timestamp: 100 });
  pinned.manager.activeRoundId = async () => { throw new Error("override should not read activeRoundId"); };
  pinned.manager.getRoundStatus = async id => { assert.equal(id, 7n); return { phase: 0n }; };
  pinned.vault.getSchedule = async () => ({ state: 0n, endsAt: 0n });
  assert.equal((await pinned.tick()).roundId, "7");
  pinned.provider.destroy();
  assert.throws(() => new DynoKeeper({ ...options, roundId: "0" }), /INVALID_ROUND_ID/);
});
test("live keeper prioritizes only the current slot and refuses pending nonces or a changed block", async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), "dyno-keeper-test-"));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));
  const keeper = new DynoKeeper({ rpcUrl: "http://127.0.0.1:1", chainId: 2020, managerAddress: "0x0000000000000000000000000000000000000001", vaultAddress: "0x0000000000000000000000000000000000000002", privateKey: Wallet.createRandom().privateKey, dryRun: false, roundId: "1", journalPath: path.join(directory, "intent.json") });
  const block = { number: 42, hash: "0x" + "aa".repeat(32), timestamp: 3601 };
  keeper.provider.send = async () => "0x7e4";
  keeper.provider.getBlock = async () => block;
  let pendingNonce = 4, sends = 0;
  keeper.provider.getTransactionCount = async (_wallet, tag) => tag === "pending" ? pendingNonce : 4;
  keeper.manager.getRoundStatus = async () => ({ phase: Phase.SETTLED });
  keeper.vault.getSchedule = async () => ({ state: Schedule.ACTIVE, startsAt: 1n, endsAt: 604801n });
  keeper.vault.getSlotStatus = async () => 0n;
  keeper.vault.terminalSlotCount = async () => 0n;
  keeper.vault.executeCurrentSlot = async override => { sends++; assert.equal(override.nonce, 4); return { hash: "0x" + "bb".repeat(32), wait: async () => ({ status: 1, hash: "0x" + "bb".repeat(32), blockNumber: 43 }) }; };
  keeper.vault.markExpiredSlots = async () => { throw new Error("expired slots must wait for another tick"); };
  assert.deepEqual((await keeper.tick()).actions.map(action => action.method), ["executeCurrentSlot"]);
  assert.equal(keeper.readJournal().state, "CONFIRMED");
  pendingNonce = 5;
  await assert.rejects(keeper.tick(), { code: "PENDING_TRANSACTION" });
  assert.equal(sends, 1);
  pendingNonce = 4;
  keeper.provider.getBlock = async tag => tag === "latest" ? block : { ...block, hash: "0x" + "cc".repeat(32) };
  await assert.rejects(keeper.tick(), { code: "CHAIN_DATA_CHANGED" });
  assert.equal(sends, 1);
  keeper.provider.destroy();
});
test("live keeper persists unresolved intent and requires reconciliation before another send", async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), "dyno-keeper-journal-"));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));
  const options = { rpcUrl: "http://127.0.0.1:1", chainId: 2020, managerAddress: "0x0000000000000000000000000000000000000001", vaultAddress: "0x0000000000000000000000000000000000000002", privateKey: Wallet.createRandom().privateKey, dryRun: false, roundId: "1", journalPath: path.join(directory, "intent.json") };
  const first = new DynoKeeper(options);
  first.writeJournal({ state: "SUBMITTED", roundId: "1", contract: "vault", method: "executeCurrentSlot", args: [], nonce: 4, hash: "0x" + "cc".repeat(32) });
  first.provider.destroy();
  const restarted = new DynoKeeper(options);
  restarted.provider.send = async () => "0x7e4";
  let checked = 0;
  restarted.provider.getTransactionReceipt = async hash => { checked++; assert.equal(hash, "0x" + "cc".repeat(32)); return null; };
  restarted.provider.getBlock = async () => { throw new Error("must not plan while unresolved"); };
  await assert.rejects(restarted.tick(), { code: "UNRESOLVED_INTENT" });
  assert.equal(checked, 1);
  restarted.provider.getTransactionReceipt = async () => ({ status: 1, blockNumber: 45 });
  await assert.rejects(restarted.tick(), { code: "UNRESOLVED_INTENT" });
  assert.equal(restarted.readJournal().state, "CONFIRMED");
  restarted.provider.destroy();
  assert.throws(() => new DynoKeeper({ ...options, journalPath: undefined }), /KEEPER_JOURNAL_REQUIRED/);
});
test("keeper never schedules catch-up and closes only at end", () => {
  assert.equal(hasExpiredPendingSlots(9, 1n, 1n), true); // public success in slot 9, older hours still pending
  assert.equal(hasExpiredPendingSlots(9, 1n, 10n), false);
  assert.equal(hasExpiredPendingSlots(0, 0n, 0n), false);
  const active = planActions({ phase: 3n, scheduleState: Schedule.ACTIVE, now: 99n, endTime: 100n, slotStatus: 0n });
  assert.deepEqual(active.map(x => x.method), ["executeCurrentSlot"]);
  const missed = planActions({ phase: 3n, scheduleState: Schedule.ACTIVE, now: 99n, endTime: 100n, slotStatus: 0n, expiredPending: true });
  assert.deepEqual(missed.map(x => x.method), ["executeCurrentSlot", "markExpiredSlots"]);
  const laterPublicSuccess = planActions({ phase: 3n, scheduleState: Schedule.ACTIVE, now: 99n, endTime: 100n, slotStatus: 1n, expiredPending: true });
  assert.deepEqual(laterPublicSuccess.map(x => x.method), ["markExpiredSlots"]);
  const ended = planActions({ phase: 3n, scheduleState: Schedule.ACTIVE, now: 100n, endTime: 100n, slotStatus: 0n });
  assert.deepEqual(ended.map(x => x.method), ["closeBuyback"]);
});
test("keeper orders draw, finalization and settlement by chain phase", () => {
  assert.equal(planActions({ phase: Phase.FROZEN, scheduleState: 0n, now: 0n, endTime: 0n }).at(0).method, "requestDraw");
  assert.equal(planActions({ phase: Phase.RANDOMNESS_READY, scheduleState: 0n, now: 0n, endTime: 0n }).at(0).method, "finalizeWinners");
  assert.equal(planActions({ phase: Phase.WINNERS_ASSIGNED, scheduleState: 0n, now: 0n, endTime: 0n }).at(0).method, "settleRound");
});
